"""The empyrical reference fixture of the Stage 20 metrics tests
(`tests/fixtures/metrics/empyrical_reference.json`, generated by
`Planning/stages/stage-20-risk-metrics/artifacts/empyrical_reference.py`)."""

import json
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Any

import pandas as pd

FIXTURE = Path(__file__).resolve().parents[3] / "fixtures" / "metrics" / "empyrical_reference.json"


@dataclass(frozen=True)
class Reference:
    """504 sessions of portfolio `returns` and `benchmark` returns (simple daily fractions) and
    the values empyrical-reloaded 0.7.2 computed on them (`values`)."""

    returns: pd.Series
    benchmark: pd.Series
    risk_free_daily: float
    periods: int
    values: MappingProxyType[str, float]


def load_reference() -> Reference:
    """Read the fixture."""
    payload: dict[str, Any] = json.loads(FIXTURE.read_text())
    index = pd.DatetimeIndex(pd.to_datetime(payload["dates"]), name="date")
    return Reference(
        returns=pd.Series(payload["returns"], index=index, name="returns"),
        benchmark=pd.Series(payload["benchmark"], index=index, name="benchmark"),
        risk_free_daily=float(payload["risk_free_daily"]),
        periods=int(payload["periods"]),
        values=MappingProxyType(dict(payload["reference"])),
    )
